export const I18N = { es, en, fr, it, de, zh };
export type Lang = keyof typeof I18N;
export const LANG_NAMES: Record<Lang, string> = {
  es: "Español",
  en: "English",
  fr: "Français",
  it: "Italiano",
  de: "Deutsch",
  zh: "中文",
};

/** First supported language among the browser's preferences, English otherwise. */
export function pickLang(preferred: readonly string[]): Lang {
  for (const tag of preferred) {
    const base = tag.toLowerCase().split("-")[0];
    if (base in I18N) return base as Lang;
  }
  return "en";
}

/** Fill [data-i18n] text, [data-i18n-html] markup, [data-i18n-aria] labels, [data-i18n-ph] placeholders. */
export function applyLang(root: ParentNode, d: Dict): void {
  const str = (el: Element, attr: string) => d[el.getAttribute(attr) as keyof Dict] as string;
  root.querySelectorAll("[data-i18n]").forEach((el) => (el.textContent = str(el, "data-i18n")));
  root
    .querySelectorAll("[data-i18n-html]")
    .forEach((el) => (el.innerHTML = str(el, "data-i18n-html")));
  root
    .querySelectorAll("[data-i18n-aria]")
    .forEach((el) => el.setAttribute("aria-label", str(el, "data-i18n-aria")));
  root
    .querySelectorAll("[data-i18n-ph]")
    .forEach((el) => el.setAttribute("placeholder", str(el, "data-i18n-ph")));
}
